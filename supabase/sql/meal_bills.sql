-- Meal plans held until served, and cafe meal bills (feature meal_bills, off unless switched on).
-- Money paid for a meal plan comes in as "Meal plans held" for the business that sold it (the stay business when it is
-- for a stay, else the main business), not as cafe sales, so it can always be refunded. The kitchen ticks each meal as
-- it is served. When it bills (any time, for example weekly), every meal served and not billed yet goes on one bill.
-- A manager marks the bill paid: then the money goes out of the selling business and in to the cafe as sales.
-- Only meal plans bought from the day this was switched on are held and billed; older plans were counted as cafe sales.
-- Also: Stripe's own fee on each online payment (stripe_fees, filled every hour from Stripe) shows as money out.

create table if not exists public.meal_bills (
  id uuid primary key default gen_random_uuid(),
  number integer generated by default as identity,
  made_at timestamptz not null default now(),
  made_by uuid references public.staff(id) on delete set null,
  n integer not null,
  amount_thb integer not null,
  lines jsonb not null default '[]'::jsonb,
  note text,
  status text not null default 'waiting' check (status in ('waiting','paid','removed')),
  paid_on date,
  paid_method text,
  paid_by uuid references public.staff(id) on delete set null,
  paid_at timestamptz
);
alter table public.meal_bills enable row level security;
revoke all on public.meal_bills from anon, authenticated;
alter table public.checkins add column if not exists meal_bill_id uuid references public.meal_bills(id) on delete set null;
create index if not exists checkins_meal_bill on public.checkins (meal_bill_id) where meal_bill_id is not null;

create table if not exists public.stripe_fees (
  session text primary key,
  account text,
  fee_thb numeric(12,2),
  gross_thb numeric(12,2),
  currency text,
  status text not null default 'ok',
  checked_at timestamptz not null default now()
);
alter table public.stripe_fees enable row level security;
revoke all on public.stripe_fees from anon, authenticated;

-- settings: from (the day meal plans started being held), pct (what the cafe bills per meal, as a percent of what the
-- guest paid for it, default 100), free_thb (what the cafe bills for a meal from a free deal, default 0)
create or replace function private.meal_cfg() returns jsonb language sql stable security definer set search_path to '' as $f$
  select coalesce((select value::jsonb from public.app_settings where key = 'meal_bills'), '{}'::jsonb)
$f$;
create or replace function private.meal_from() returns date language sql stable security definer set search_path to '' as $f$
  select coalesce(nullif(private.meal_cfg()->>'from','')::date, date '9999-12-31')
$f$;
-- a meal plan whose money is held: only cafe meals, sold on or after the start day, with the feature on
create or replace function private.meal_held(p_covers text[], p_day date) returns boolean language sql stable security definer set search_path to '' as $f$
  select coalesce(p_covers = array['Cafe meal'], false) and p_day >= private.meal_from() and private.feature('meal_bills', false)
$f$;
create or replace function private.meal_biz(p_stay uuid, p_for_stay uuid) returns text language sql stable security definer set search_path to '' as $f$
  select case when coalesce(p_stay, p_for_stay) is not null then private.biz_stay() else private.biz_main() end
$f$;
-- one meal: what the guest paid for it, and what the cafe bills for it
create or replace function private.meal_value(k public.purchases) returns numeric language sql stable security definer set search_path to '' as $f$
  select case when coalesce(k.visit_limit, 0) > 0 then greatest(0, k.price_thb - coalesce(k.fee_thb,0) - coalesce(k.tax_thb,0))::numeric / k.visit_limit else 0 end
$f$;
create or replace function private.meal_rate(k public.purchases) returns integer language sql stable security definer set search_path to '' as $f$
  select case when private.meal_value(k) > 0 then round(private.meal_value(k) * coalesce(nullif(private.meal_cfg()->>'pct','')::numeric, 100) / 100)::int
              else coalesce(nullif(private.meal_cfg()->>'free_thb','')::int, 0) end
$f$;
create or replace function private.meal_plan_name(p text) returns text language sql immutable set search_path to '' as $f$
  select coalesce(nullif(btrim(regexp_replace(coalesce(p,''), ',\s*\d+\s+(days?|meals?)\s*$', '', 'i')), ''), 'Meals')
$f$;
create or replace function private.meal_staff_ok() returns boolean language sql stable security definer set search_path to '' as $f$
  select coalesce(private.staff_role() in ('manager','front_desk','resort','kitchen'), false)
$f$;

-- the kitchen list: everyone with a meal plan running today, meals left and served today
create or replace function public.meal_plans_today() returns jsonb language plpgsql stable security definer set search_path to '' as $f$
declare d date := private.bkk_today();
begin
  if not private.meal_staff_ok() then raise exception 'Only staff can see meal plans.'; end if;
  return coalesce((select jsonb_agg(x order by x->>'room' nulls last, x->>'who') from (
    select jsonb_build_object('id', k.id, 'customer_id', k.customer_id, 'who', c.name, 'plan', k.package_name, 'left', coalesce(k.visits_left, k.visit_limit), 'limit', k.visit_limit,
      'until', k.expires_on, 'not_paid', k.ordered_in_app and not k.paid,
      'room', (select r.name from public.stays s join public.rooms r on r.id = s.room_id where s.customer_id = k.customer_id and s.status in ('booked','in') and d between s.check_in and s.check_out order by s.check_in limit 1),
      'note', (select string_agg(nullif(btrim(fp.note),''), '. ') from public.food_plans fp where fp.customer_id = k.customer_id and not coalesce(fp.removed,false) and fp.starts_on <= d and (fp.ends_on is null or fp.ends_on >= d)),
      'today', (select coalesce(jsonb_agg(jsonb_build_object('id', ci.id, 'at', ci.checked_in_at, 'billed', ci.meal_bill_id is not null) order by ci.checked_in_at), '[]'::jsonb)
                from public.checkins ci where ci.purchase_id = k.id and ci.day = d and ci.facility = 'Cafe meal')) x
    from public.purchases k join public.customers c on c.id = k.customer_id
    where k.covers = array['Cafe meal'] and not k.cancelled and k.refunded_at is null
      and (k.starts_on is null or k.starts_on <= d) and (k.expires_on is null or k.expires_on >= d)
      and (coalesce(k.visits_left, k.visit_limit, 1) > 0 or exists (select 1 from public.checkins ci where ci.purchase_id = k.id and ci.day = d))) q), '[]'::jsonb);
end $f$;

create or replace function public.meal_serve(p_purchase uuid) returns uuid language plpgsql security definer set search_path to '' as $f$
declare k public.purchases;
begin
  if not private.meal_staff_ok() then raise exception 'Only staff can tick meals.'; end if;
  select * into k from public.purchases where id = p_purchase;
  if k.id is null or k.covers is distinct from array['Cafe meal'] then raise exception 'That is not a meal plan.'; end if;
  return private.do_check_in(k.customer_id, k.id, null, 'Cafe meal', private.my_staff_id());
end $f$;

-- a meal ticked by mistake: today only (a manager any day), and not once it is on a bill
create or replace function public.meal_unserve(p_checkin uuid) returns void language plpgsql security definer set search_path to '' as $f$
declare ci public.checkins;
begin
  if not private.meal_staff_ok() then raise exception 'Only staff can change meals.'; end if;
  select * into ci from public.checkins where id = p_checkin and facility = 'Cafe meal' for update;
  if ci.id is null then raise exception 'That meal was not found.'; end if;
  if ci.meal_bill_id is not null then raise exception 'That meal is already on a bill.'; end if;
  if ci.day <> private.bkk_today() and private.staff_role() <> 'manager' then raise exception 'Only a manager can take off a meal from another day.'; end if;
  -- the meal goes back on the plan by itself (trigger checkins_restore_visit)
  delete from public.checkins where id = ci.id;
end $f$;

-- meals served that can go on a bill: from held meal plans, served up to today, not on a bill yet
create or replace function private.meal_unbilled() returns table(ci uuid, day date, b text, plan text, rate integer) language sql stable security definer set search_path to '' as $f$
  select ci.id, ci.day, private.meal_biz(k.stay_id, k.for_stay), private.meal_plan_name(k.package_name), private.meal_rate(k)
  from public.checkins ci join public.purchases k on k.id = ci.purchase_id
  where ci.facility = 'Cafe meal' and ci.meal_bill_id is null and k.covers = array['Cafe meal']
    and ci.day >= private.meal_from() and coalesce(k.purchased_on, ci.day) >= private.meal_from() and ci.day <= private.bkk_today()
$f$;

create or replace function public.meal_bills_data() returns jsonb language plpgsql security definer set search_path to '' as $f$
declare cfg jsonb; f date; mgr boolean := private.staff_role() = 'manager';
begin
  if not private.meal_staff_ok() then raise exception 'Only staff can see meal bills.'; end if;
  if not private.feature('meal_bills', false) then return jsonb_build_object('off', true); end if;
  -- the first time: meal plans are held from today
  if not exists (select 1 from public.app_settings where key = 'meal_bills') then
    insert into public.app_settings(key, value) values ('meal_bills', jsonb_build_object('from', private.bkk_today(), 'pct', 100, 'free_thb', 0)::text) on conflict (key) do nothing;
  end if;
  cfg := private.meal_cfg(); f := private.meal_from();
  return jsonb_build_object('from', f, 'pct', coalesce(nullif(cfg->>'pct','')::numeric, 100), 'free_thb', coalesce(nullif(cfg->>'free_thb','')::int, 0), 'manager', mgr,
    'unbilled', coalesce((select jsonb_agg(jsonb_build_object('plan', u.plan, 'n', u.n, 'amount', u.a, 'first', u.d1, 'last', u.d2) order by u.plan)
       from (select plan, count(*) n, sum(rate) a, min(day) d1, max(day) d2 from private.meal_unbilled() group by plan) u), '[]'::jsonb),
    'bills', coalesce((select jsonb_agg(jsonb_build_object('id', mb.id, 'number', mb.number, 'at', mb.made_at, 'by', (select s.name from public.staff s where s.id = mb.made_by), 'n', mb.n, 'amount', mb.amount_thb,
        'lines', mb.lines, 'note', mb.note, 'status', mb.status, 'paid_on', mb.paid_on, 'method', mb.paid_method, 'paid_by', (select s.name from public.staff s where s.id = mb.paid_by),
        'first', (select min(ci.day) from public.checkins ci where ci.meal_bill_id = mb.id), 'last', (select max(ci.day) from public.checkins ci where ci.meal_bill_id = mb.id)) order by mb.made_at desc)
       from public.meal_bills mb where mb.status = 'waiting' or (mb.status = 'paid' and mb.paid_on >= private.bkk_today() - 60)), '[]'::jsonb),
    -- only the owner and managers see what is held: meals not served yet on meal plans that are paid
    'held', case when mgr then (select jsonb_build_object('meals', coalesce(sum(coalesce(k.visits_left, k.visit_limit)),0), 'thb', coalesce(round(sum(coalesce(k.visits_left, k.visit_limit) * private.meal_value(k))),0), 'plans', count(*))
       from public.purchases k where k.covers = array['Cafe meal'] and not k.cancelled and k.refunded_at is null and k.purchased_on >= f and k.paid_thb >= k.price_thb and k.price_thb > 0) end);
end $f$;

create or replace function public.meal_bill_send(p_note text default null) returns jsonb language plpgsql security definer set search_path to '' as $f$
declare v uuid; vn int; va int; ls jsonb; ids uuid[];
begin
  if not private.meal_staff_ok() then raise exception 'Only staff can send a meal bill.'; end if;
  if not private.feature('meal_bills', false) then raise exception 'Meal bills are switched off.'; end if;
  -- the meals on this bill, locked so two people billing at once cannot bill a meal twice
  select array_agg(u.ci) into ids from private.meal_unbilled() u;
  if ids is null then raise exception 'There are no meals to bill. Meals show here once they are ticked as served.'; end if;
  perform 1 from public.checkins where id = any(ids) for update;
  select array_agg(id) into ids from public.checkins where id = any(ids) and meal_bill_id is null;
  if ids is null then raise exception 'Those meals were just billed by someone else.'; end if;
  select coalesce(jsonb_agg(jsonb_build_object('b', g.b, 'plan', g.plan, 'n', g.cn, 'rate', case when g.r1 = g.r2 then g.r1 end, 'amount', g.am) order by g.plan, g.b), '[]'::jsonb),
         coalesce(sum(g.cn),0), coalesce(sum(g.am),0) into ls, vn, va
  from (select u.b, u.plan, count(*)::int cn, min(u.rate) r1, max(u.rate) r2, sum(u.rate)::int am from private.meal_unbilled() u where u.ci = any(ids) group by u.b, u.plan) g;
  insert into public.meal_bills(made_by, n, amount_thb, lines, note) values (private.my_staff_id(), vn, va, ls, nullif(left(btrim(coalesce(p_note,'')),500),'')) returning id into v;
  update public.checkins set meal_bill_id = v where id = any(ids);
  return jsonb_build_object('id', v, 'n', vn, 'amount', va);
end $f$;

create or replace function public.meal_bill_pay(p_id uuid, p_method text, p_day date default null) returns void language plpgsql security definer set search_path to '' as $f$
begin
  if private.staff_role() is distinct from 'manager' then raise exception 'Only a manager can mark a meal bill paid.'; end if;
  if p_method not in ('cash','transfer','card','qr','other') then raise exception 'Choose how it was paid.'; end if;
  update public.meal_bills set status = 'paid', paid_on = coalesce(p_day, private.bkk_today()), paid_method = p_method, paid_by = private.my_staff_id(), paid_at = now()
  where id = p_id and status = 'waiting';
  if not found then raise exception 'That bill is already paid or was removed.'; end if;
end $f$;

-- undo: a paid bill goes back to waiting; a waiting bill is removed and its meals can be billed again
create or replace function public.meal_bill_undo(p_id uuid) returns text language plpgsql security definer set search_path to '' as $f$
declare s text;
begin
  if private.staff_role() is distinct from 'manager' then raise exception 'Only a manager can change a meal bill.'; end if;
  select status into s from public.meal_bills where id = p_id for update;
  if s = 'paid' then update public.meal_bills set status = 'waiting', paid_on = null, paid_method = null, paid_by = null, paid_at = null where id = p_id; return 'waiting'; end if;
  if s = 'waiting' then update public.checkins set meal_bill_id = null where meal_bill_id = p_id; update public.meal_bills set status = 'removed' where id = p_id; return 'removed'; end if;
  raise exception 'That bill was not found.';
end $f$;

create or replace function public.meal_bills_settings_save(p jsonb) returns void language plpgsql security definer set search_path to '' as $f$
declare pct numeric; fr int;
begin
  if private.staff_role() is distinct from 'manager' then raise exception 'Only a manager can change this.'; end if;
  begin pct := nullif(p->>'pct','')::numeric; exception when others then raise exception 'Type a percent.'; end;
  begin fr := nullif(p->>'free_thb','')::int; exception when others then raise exception 'Type an amount.'; end;
  if pct is null or pct < 0 or pct > 100 then raise exception 'The percent is from 0 to 100.'; end if;
  if coalesce(fr,0) < 0 then raise exception 'The amount cannot be below 0.'; end if;
  insert into public.app_settings(key, value) values ('meal_bills', jsonb_build_object('from', private.bkk_today(), 'pct', pct, 'free_thb', coalesce(fr,0))::text)
  on conflict (key) do update set value = (public.app_settings.value::jsonb || jsonb_build_object('pct', pct, 'free_thb', coalesce(fr,0)))::text;
end $f$;

-- Stripe fees: which payments still need their fee, and saving what Stripe says (the stripe-report function, every hour)
create or replace function public.stripe_fees_todo(p_limit integer default 40) returns jsonb language sql stable security definer set search_path to '' as $f$
  select coalesce(jsonb_agg(jsonb_build_object('session', s, 'thb', thb)), '[]'::jsonb) from (
    select s, sum(thb) thb from (
      select split_part(p.stripe_session, ':', 1) s, p.amount_thb thb from public.payments p
        where p.stripe_session is not null and not p.voided and p.day >= private.bkk_today() - 400
      union all
      select split_part(o.stripe_session, ':', 1), o.total_thb from public.shop_orders o
        where o.stripe_session is not null and o.paid_at is not null and o.paid_at > now() - interval '400 days') a
    where s ~ '^(cs|pi|ch)_' and not exists (select 1 from public.stripe_fees f where f.session = a.s and (f.status in ('ok','none') or f.checked_at > now() - interval '1 hour'))
    group by s order by s limit greatest(1, least(100, p_limit))) q
$f$;
create or replace function public.stripe_fees_save(p jsonb) returns integer language plpgsql security definer set search_path to '' as $f$
declare r jsonb; n int := 0;
begin
  for r in select * from jsonb_array_elements(coalesce(p,'[]'::jsonb)) loop
    insert into public.stripe_fees(session, account, fee_thb, gross_thb, currency, status, checked_at)
    values (r->>'session', r->>'account', nullif(r->>'fee_thb','')::numeric, nullif(r->>'gross_thb','')::numeric, r->>'currency', coalesce(nullif(r->>'status',''),'ok'), now())
    on conflict (session) do update set account = excluded.account, fee_thb = excluded.fee_thb, gross_thb = excluded.gross_thb, currency = excluded.currency, status = excluded.status, checked_at = now();
    n := n + 1;
  end loop;
  return n;
end $f$;

revoke all on function public.stripe_fees_todo(integer), public.stripe_fees_save(jsonb) from public, anon, authenticated;
grant execute on function public.stripe_fees_todo(integer), public.stripe_fees_save(jsonb) to service_role;
revoke all on function public.meal_plans_today(), public.meal_serve(uuid), public.meal_unserve(uuid), public.meal_bills_data(), public.meal_bill_send(text),
  public.meal_bill_pay(uuid,text,date), public.meal_bill_undo(uuid), public.meal_bills_settings_save(jsonb) from public, anon;
grant execute on function public.meal_plans_today(), public.meal_serve(uuid), public.meal_unserve(uuid), public.meal_bills_data(), public.meal_bill_send(text),
  public.meal_bill_pay(uuid,text,date), public.meal_bill_undo(uuid), public.meal_bills_settings_save(jsonb) to authenticated;
revoke all on function private.meal_cfg(), private.meal_from(), private.meal_held(text[],date), private.meal_biz(uuid,uuid), private.meal_value(public.purchases),
  private.meal_rate(public.purchases), private.meal_staff_ok(), private.meal_unbilled() from public, anon, authenticated;

-- Accounts: held meal plan money, paid cafe bills, and Stripe fees. Patches private.acc_lines, checking each change applied.
do $p$
declare d text; n text; part text;
begin
  if to_regprocedure('private.acc_lines(date,date)') is null then raise notice 'no acc_lines here, skipped'; return; end if;
  d := pg_get_functiondef('private.acc_lines(date,date)'::regprocedure);
  if position('meal_held' in d) > 0 then raise notice 'acc_lines already patched'; return; end if;
  n := d;
  -- payments: a held meal plan belongs to the business that sold it, department Meal plans, category Meal plans held
  part := replace(n, $$p.fee_business, ov.b, case when k.id is not null and private.purchase_zone(k.covers, k.package_name)='cafe'$$,
                     $$p.fee_business, case when private.meal_held(k.covers, p.day) then private.meal_biz(k.stay_id, k.for_stay) end, ov.b, case when k.id is not null and private.purchase_zone(k.covers, k.package_name)='cafe'$$);
  if part = n then raise notice 'acc_lines: older version (payments business), skipped'; return; end if; n := part;
  part := replace(n, $$when p.is_fee then coalesce(p.fee_dept, 'Card fees') when ov.d is not null$$,
                     $$when p.is_fee then coalesce(p.fee_dept, 'Card fees') when private.meal_held(k.covers, p.day) then 'Meal plans' when ov.d is not null$$);
  if part = n then raise notice 'acc_lines: older version (payments department), skipped'; return; end if; n := part;
  part := replace(n, $$when x.part = 'tax' then 'Tax collected' else 'Sales' end, p.method$$,
                     $$when x.part = 'tax' then 'Tax collected' when private.meal_held(k.covers, p.day) then 'Meal plans held' else 'Sales' end, p.method$$);
  if part = n then raise notice 'acc_lines: older version (payments category), skipped'; return; end if; n := part;
  -- packages sold on the till
  part := replace(n, $$coalesce(ov.b, case when private.purchase_zone(k.covers, k.package_name)='cafe' then private.biz_cafe()$$,
                     $$coalesce(case when private.meal_held(k.covers, (o.paid_at at time zone 'Asia/Bangkok')::date) then private.meal_biz(k.stay_id, k.for_stay) end, ov.b, case when private.purchase_zone(k.covers, k.package_name)='cafe' then private.biz_cafe()$$);
  if part = n then raise notice 'acc_lines: older version (till business), skipped'; return; end if; n := part;
  part := replace(n, $$coalesce(ov.d, case when private.purchase_zone(k.covers, k.package_name)='cafe' then private.dept_cafe()$$,
                     $$coalesce(case when private.meal_held(k.covers, (o.paid_at at time zone 'Asia/Bangkok')::date) then 'Meal plans' end, ov.d, case when private.purchase_zone(k.covers, k.package_name)='cafe' then private.dept_cafe()$$);
  if part = n then raise notice 'acc_lines: older version (till department), skipped'; return; end if; n := part;
  part := replace(n, $$'in', coalesce(k.package_name, i.name), 'Sales', o.method$$,
                     $$'in', coalesce(k.package_name, i.name), case when private.meal_held(k.covers, (o.paid_at at time zone 'Asia/Bangkok')::date) then 'Meal plans held' else 'Sales' end, o.method$$);
  if part = n then raise notice 'acc_lines: older version (till category), skipped'; return; end if; n := part;
  -- new parts at the end: paid cafe meal bills, and Stripe fees
  part := replace(n, $$from public.acc_entries e where not e.voided and e.day between p_from and p_to$$, $$from public.acc_entries e where not e.voided and e.day between p_from and p_to
  union all
  -- cafe meal bills, paid: out of the business that holds the meal plan money, in to the cafe as sales
  select mb.paid_on, l->>'b', 'Meal plans', 'out', 'Cafe meal bill #' || mb.number || ': ' || (l->>'n') || ' x ' || (l->>'plan'), 'Cafe meals', mb.paid_method, (l->>'amount')::numeric, 'meal_bill', mb.id, null
  from public.meal_bills mb cross join jsonb_array_elements(mb.lines) l where mb.status = 'paid' and mb.paid_on between p_from and p_to and (l->>'amount')::numeric <> 0
  union all
  select mb.paid_on, private.biz_cafe(), private.dept_cafe(), 'in', 'Meal plans served, bill #' || mb.number || ': ' || (l->>'n') || ' x ' || (l->>'plan'), 'Sales', mb.paid_method, (l->>'amount')::numeric, 'meal_bill', mb.id, null
  from public.meal_bills mb cross join jsonb_array_elements(mb.lines) l where mb.status = 'paid' and mb.paid_on between p_from and p_to and (l->>'amount')::numeric <> 0
  union all
  -- Stripe's own fee on online card payments: sales less Stripe fees is what reaches the bank
  select p.day,
    coalesce(p.fee_business, case when private.meal_held(k.covers, p.day) then private.meal_biz(k.stay_id, k.for_stay) end, (select pg.acc_business from public.packages pg where pg.id = k.package_id),
      case when k.id is not null and private.purchase_zone(k.covers, k.package_name)='cafe' then private.biz_cafe() when k.id is not null and private.purchase_zone(k.covers, k.package_name)='tours' then private.biz_tours()
           when p.stay_id is not null then private.biz_stay() else private.biz_main() end),
    'Card fees', 'out', 'Stripe fee: ' || case when p.stay_id is not null then 'stay payment' when p.private_id is not null then 'private' else coalesce(k.package_name, 'payment') end, 'Bank and card fees', 'stripe',
    round(sf.fee_thb * p.amount_thb / nullif(tot.a, 0), 2), 'stripe_fee', p.id, null
  from public.payments p join public.stripe_fees sf on sf.session = split_part(p.stripe_session, ':', 1) and sf.fee_thb > 0
    cross join lateral (select sum(q.amount_thb) a from public.payments q where not q.voided and q.stripe_session is not null and split_part(q.stripe_session, ':', 1) = sf.session) tot
    left join public.purchases k on k.id = p.purchase_id
