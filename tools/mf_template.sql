-- Muay Friend free: builds the template of the whole app database (schemas public and private) and sends it to the
-- shared free database (project bnglnfdgptvnmugntiom, table mf.template), where every new gym is made from it.
-- Run on the database whose structure is the reference (live), after app changes, with the import key from mf.keys.
-- Names: public -> __P__, private -> __Q__ (the gym's own schemas are put in at provision time).
-- Replace :KEY: and :ANON: before running. Only the structure is copied, never any data.
set search_path = pg_catalog;
with
rn as (select 1),
tbl as (
  select c.oid, n.nspname, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.relacl
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in ('public','private') and c.relkind = 'r' and c.relname not in ('mf_leads')),
s as (
  -- 1 schemas
  select 1 phase, 'schema' kind, 'schemas' name, 'create schema if not exists __P__; create schema if not exists __Q__;' sql
  union all select 1, 'schema', 'usage', 'grant usage on schema __P__ to anon, authenticated, service_role; grant usage on schema __Q__ to authenticated, service_role;'
  -- 2 sequences
  union all select 2, 'sequence', n.nspname||'.'||c.relname, format('create sequence if not exists %I.%I;', n.nspname, c.relname)
    from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname in ('public','private') and c.relkind = 'S'
  -- 3 tables (columns only)
  union all select 3, 'table', t.nspname||'.'||t.relname,
    format('create table %I.%I (%s);', t.nspname, t.relname, (select string_agg(format('%I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end,
        case when a.attnotnull then ' not null' else '' end), ', ' order by a.attnum)
      from pg_attribute a where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
    from tbl t
  -- 4 functions
  union all select 4, 'function', n.nspname||'.'||p.proname, pg_get_functiondef(p.oid)||';'
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname in ('public','private') and p.prokind in ('f','p')
  -- 5 column defaults
  union all select 5, 'default', t.nspname||'.'||t.relname||'.'||a.attname, format('alter table %I.%I alter column %I set default %s;', t.nspname, t.relname, a.attname, pg_get_expr(d.adbin, d.adrelid))
    from tbl t join pg_attrdef d on d.adrelid = t.oid join pg_attribute a on a.attrelid = t.oid and a.attnum = d.adnum
  -- 6 keys and checks, 7 foreign keys
  union all select case when co.contype = 'f' then 7 else 6 end, 'constraint', t.nspname||'.'||t.relname||'.'||co.conname,
    format('alter table %I.%I add constraint %I %s;', t.nspname, t.relname, co.conname, pg_get_constraintdef(co.oid))
    from tbl t join pg_constraint co on co.conrelid = t.oid where co.contype in ('p','u','c','x','f')
  -- 8 indexes (not the ones made by constraints)
  union all select 8, 'index', i.schemaname||'.'||i.indexname, i.indexdef||';'
    from pg_indexes i join tbl t on t.nspname = i.schemaname and t.relname = i.tablename
    where not exists (select 1 from pg_constraint co where co.conname = i.indexname and co.conrelid = t.oid)
  -- 9 triggers
  union all select 9, 'trigger', t.nspname||'.'||t.relname||'.'||tg.tgname, pg_get_triggerdef(tg.oid)||';'
    from tbl t join pg_trigger tg on tg.tgrelid = t.oid where not tg.tgisinternal
  -- 10 row security and policies
  union all select 10, 'rls', t.nspname||'.'||t.relname, format('alter table %I.%I enable row level security;', t.nspname, t.relname)||case when t.relforcerowsecurity then format(' alter table %I.%I force row level security;', t.nspname, t.relname) else '' end
    from tbl t where t.relrowsecurity
  union all select 10, 'policy', po.schemaname||'.'||po.tablename||'.'||po.policyname,
    format('create policy %I on %I.%I as %s for %s to %s%s%s;', po.policyname, po.schemaname, po.tablename, po.permissive, po.cmd,
      (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ') from unnest(po.roles) r),
      case when po.qual is not null then ' using ('||po.qual||')' else '' end,
      case when po.with_check is not null then ' with check ('||po.with_check||')' else '' end)
    from pg_policies po join tbl t on t.nspname = po.schemaname and t.relname = po.tablename
  -- 11 grants on tables and sequences
  union all select 11, 'grant', n.nspname||'.'||c.relname, format('grant %s on %s %I.%I to %s;', x.privilege_type, case c.relkind when 'S' then 'sequence' else 'table' end, n.nspname, c.relname,
      case when x.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(x.grantee)) end)
    from pg_class c join pg_namespace n on n.oid = c.relnamespace, aclexplode(c.relacl) x
    where n.nspname in ('public','private') and c.relkind in ('r','S') and c.relname not in ('mf_leads')
      and x.grantee <> c.relowner and (x.grantee = 0 or pg_get_userbyid(x.grantee) in ('anon','authenticated','service_role'))
  -- 11 column grants (tables where only some columns may be read or changed, for example staff)
  union all select 11, 'colgrant', n.nspname||'.'||c.relname||'.'||a.attname, format('grant %s (%I) on table %I.%I to %s;', x.privilege_type, a.attname, n.nspname, c.relname,
      case when x.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(x.grantee)) end)
    from pg_attribute a join pg_class c on c.oid = a.attrelid join pg_namespace n on n.oid = c.relnamespace, aclexplode(a.attacl) x
    where n.nspname in ('public','private') and c.relkind = 'r' and c.relname not in ('mf_leads') and a.attnum > 0 and not a.attisdropped and a.attacl is not null
      and (x.grantee = 0 or pg_get_userbyid(x.grantee) in ('anon','authenticated','service_role'))
  -- 11 function rights: take away the default "everyone may run it", then give back what the app gives
  union all select 11, 'revoke', n.nspname||'.'||p.proname, format('revoke all on function %I.%I(%s) from public;', n.nspname, p.proname, pg_get_function_identity_arguments(p.oid))
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname in ('public','private') and p.prokind in ('f','p') and p.proacl is not null
  union all select 11, 'execute', n.nspname||'.'||p.proname, format('grant execute on function %I.%I(%s) to %s;', n.nspname, p.proname, pg_get_function_identity_arguments(p.oid),
      case when x.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(x.grantee)) end)
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace, aclexplode(p.proacl) x
    where n.nspname in ('public','private') and p.prokind in ('f','p') and p.proacl is not null and x.grantee <> p.proowner
      and (x.grantee = 0 or pg_get_userbyid(x.grantee) in ('anon','authenticated','service_role'))
),
named as (
  select phase, kind, name,
    regexp_replace(regexp_replace(sql, '\mpublic\.(?=["a-z_])', '__P__.', 'g'), '\mprivate\.(?=["a-z_])', '__Q__.', 'g') sql,
    phase * 100000 + row_number() over (partition by phase order by kind, name) ord
  from s),
chunks as (
  select (ord / 150) grp, jsonb_agg(jsonb_build_object('ord', ord, 'phase', phase, 'kind', kind, 'name', name, 'sql', sql)) rows_ from named group by ord / 150)
select count(*) posts, sum(jsonb_array_length(rows_)) statements,
  max(net.http_post('https://bnglnfdgptvnmugntiom.supabase.co/rest/v1/rpc/mf_template_put',
    jsonb_build_object('p_secret', ':KEY:', 'p_rows', rows_), '{}'::jsonb,
    jsonb_build_object('Content-Type', 'application/json', 'apikey', ':ANON:'), 30000)) last_request
from chunks;
